export function t(lang, key, vars) {
  const dict = I18N[lang] || I18N.zh;
  const raw = dict[key] || '';
  if (!vars) return raw;
  return String(raw).replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] === undefined ? `{${k}}` : String(vars[k]),
  );
}
